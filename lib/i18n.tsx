export function errorText(lang: Lang, e: unknown) {
  const msg = (e as { message?: string })?.message ?? "";
  const known = errors[msg];
  if (known) return known[lang === "ar" ? 1 : 0];
  if (/anonymous/i.test(msg)) return "Anonymous sign-ins are disabled in Supabase Auth settings.";
  if (/fetch|network|Failed to/i.test(msg)) return lang === "ar" ? "مشكلة في الاتصال. حاول مجدداً." : "Connection problem. Try again.";
  return lang === "ar" ? "حدث خطأ. حاول مجدداً." : "Something went wrong. Try again.";
}

type Ctx = { lang: Lang; t: (k: Key) => string; toggle: () => void };
const LangContext = createContext<Ctx | null>(null);

export function LangProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initial);
  const toggle = () => {
    const next: Lang = lang === "ar" ? "en" : "ar";
    document.cookie = `lang=${next};path=/;max-age=31536000;samesite=lax`;
    document.documentElement.lang = next;
    document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
    setLang(next);
  };
  const t = (k: Key) => dict[k][lang === "ar" ? 1 : 0];
  return <LangContext value={{ lang, t, toggle }}>{children}</LangContext>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang outside LangProvider");
  return ctx;
}
